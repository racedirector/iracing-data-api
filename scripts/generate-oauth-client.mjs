import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = process.env.OPENAPI_DOC || path.join(root, "openapi/oauth.json");
const output =
  process.env.OUTPUT_FILE ||
  path.join(root, "packages/oauth/client/src/generated/oauth-api.ts");

const expectedOperations = [
  ["get", "/iracing/profile", "getProfile"],
  ["get", "/sessions", "getSessions"],
  ["post", "/revoke/current", "revokeCurrent"],
  ["post", "/revoke/sessions", "revokeSessions"],
  ["post", "/revoke/client", "revokeClient"],
  ["get", "/authorize", "authorize"],
  ["post", "/token", "exchangeToken"],
];

function assertOperation(document, method, route, operationId) {
  const operation = document.paths?.[route]?.[method];
  if (operation?.operationId !== operationId) {
    throw new Error(
      `Expected ${method.toUpperCase()} ${route} to have operationId ${operationId}; received ${String(operation?.operationId)}`,
    );
  }
}

const source = fs.readFileSync(input, "utf8");
const document = JSON.parse(source);
if (document.openapi !== "3.1.1") {
  throw new Error(`Expected OAuth OpenAPI 3.1.1; received ${document.openapi}`);
}
for (const [method, route, operationId] of expectedOperations) {
  assertOperation(document, method, route, operationId);
}

const basePath = document.servers?.[0]?.url;
if (typeof basePath !== "string" || !basePath.startsWith("https://")) {
  throw new Error("OAuth OpenAPI must declare an HTTPS server URL");
}

const generated = `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/generate-oauth-client.mjs from openapi/oauth.json.
 * DO NOT EDIT BY HAND.
 */

import {
  OAuthProfileResponseSchema,
  OAuthSessionsSchema,
  OAuthTokenResponseSchema,
  type OAuthAuthorizeParameters,
  type OAuthProfileResponse,
  type OAuthRevokeCurrentSessionParameters,
  type OAuthRevokeSessionsParameters,
  type OAuthSessions,
  type OAuthTokenParameters,
  type OAuthTokenResponse,
} from "@iracing-data/oauth-schema";

export type OAuthAccessTokenProvider =
  | string
  | Promise<string>
  | (() => string | Promise<string>);

export interface OAuthApiClientGeneratedOptions {
  accessToken?: OAuthAccessTokenProvider;
  basePath?: string;
  fetchApi?: typeof fetch;
  requestTimeoutMs?: number;
}

export class OAuthApiHttpError extends Error {
  readonly requestId?: string;

  constructor(readonly response: Response) {
    super("OAuth API request failed with HTTP " + response.status + ".");
    this.name = "OAuthApiHttpError";
    this.requestId = response.headers.get("x-request-id") ?? undefined;
  }
}

export class OAuthApiContractError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "OAuthApiContractError";
  }
}

function encodeForm(values: Record<string, unknown>) {
  const form = new URLSearchParams();
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined) continue;
    form.set(key, Array.isArray(value) ? value.join(",") : String(value));
  }
  return form;
}

function encodeQuery(values: Record<string, unknown>) {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined) continue;
    query.set(key, String(value));
  }
  return query;
}

export class OAuthApiClientGenerated {
  private readonly accessToken?: OAuthAccessTokenProvider;
  private readonly basePath: string;
  private readonly fetchApi: typeof fetch;
  private readonly requestTimeoutMs: number;

  constructor(options: OAuthApiClientGeneratedOptions = {}) {
    this.accessToken = options.accessToken;
    this.basePath = (options.basePath ?? ${JSON.stringify(basePath)}).replace(/\\/+$/, "");
    this.fetchApi = options.fetchApi ?? fetch;
    this.requestTimeoutMs = options.requestTimeoutMs ?? 30_000;
  }

  createAuthorizationUrl(parameters: OAuthAuthorizeParameters) {
    const query = encodeQuery(parameters as Record<string, unknown>);
    return new URL(this.basePath + "/authorize?" + query.toString());
  }

  async exchangeToken(parameters: OAuthTokenParameters) {
    const response = await this.request(
      "/token",
      {
        method: "POST",
        headers: {
          Accept: "application/json",
          "Content-Type": "application/x-www-form-urlencoded",
        },
        body: encodeForm(parameters as Record<string, unknown>),
      },
      false,
    );
    return this.parseJson(response, OAuthTokenResponseSchema.parse) as Promise<OAuthTokenResponse>;
  }

  async getProfile() {
    const response = await this.request("/iracing/profile", {
      method: "GET",
      headers: { Accept: "application/json" },
    });
    return this.parseJson(response, OAuthProfileResponseSchema.parse) as Promise<OAuthProfileResponse>;
  }

  async getSessions() {
    const response = await this.request("/sessions", {
      method: "GET",
      headers: { Accept: "application/json" },
    });
    return this.parseJson(response, OAuthSessionsSchema.parse) as Promise<OAuthSessions>;
  }

  async revokeCurrent(parameters: OAuthRevokeCurrentSessionParameters = {}) {
    await this.request("/revoke/current", {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: encodeForm(parameters as Record<string, unknown>),
    });
  }

  async revokeSessions(parameters: OAuthRevokeSessionsParameters) {
    await this.request("/revoke/sessions", {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: encodeForm(parameters as Record<string, unknown>),
    });
  }

  async revokeClient() {
    await this.request("/revoke/client", { method: "POST" });
  }

  private async resolveAccessToken() {
    const provider = this.accessToken;
    if (!provider) {
      throw new Error("OAuth API access token is required for this operation.");
    }
    return await (typeof provider === "function" ? provider() : provider);
  }

  private async request(
    route: string,
    init: RequestInit,
    requiresAuth = true,
  ) {
    const headers = new Headers(init.headers);
    if (requiresAuth) {
      headers.set("Authorization", "Bearer " + (await this.resolveAccessToken()));
    }

    let response: Response;
    try {
      response = await this.fetchApi(this.basePath + route, {
        ...init,
        headers,
        redirect: "error",
        signal: init.signal ?? AbortSignal.timeout(this.requestTimeoutMs),
      });
    } catch (error) {
      const reason = error instanceof Error ? error.name : "unknown error";
      throw new OAuthApiContractError(
        "OAuth API request failed before a response was received: " + reason,
      );
    }

    if (!response.ok) throw new OAuthApiHttpError(response);
    return response;
  }

  private async parseJson<T>(
    response: Response,
    parse: (value: unknown) => T,
  ): Promise<T> {
    if (!response.headers.get("content-type")?.includes("application/json")) {
      throw new OAuthApiContractError("OAuth API response was not JSON.");
    }

    let value: unknown;
    try {
      value = await response.json();
    } catch {
      throw new OAuthApiContractError("OAuth API response contained invalid JSON.");
    }

    try {
      return parse(value);
    } catch {
      throw new OAuthApiContractError(
        "OAuth API response did not match the maintained contract.",
      );
    }
  }
}
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, generated);
console.info(
  `[oauth-client] Generated ${path.relative(root, output)} from ${path.relative(root, input)}`,
);
